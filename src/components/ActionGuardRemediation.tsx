import React, { useState } from 'react';
import { 
  ShieldCheck, 
  CheckSquare, 
  Square, 
  Copy, 
  Check, 
  Download, 
  AlertTriangle, 
  FileCheck,
  ExternalLink,
  LifeBuoy
} from 'lucide-react';
import { RemediationStep, ScanResult } from '../types';

interface ActionGuardRemediationProps {
  result: ScanResult;
}

export const ActionGuardRemediation: React.FC<ActionGuardRemediationProps> = ({ result }) => {
  const { remediationSteps, safeActions, threatPercentage, headline, id, timestamp, inputDomain } = result;
  const [completedSteps, setCompletedSteps] = useState<Record<number, boolean>>({});
  const [copiedReport, setCopiedReport] = useState(false);

  const toggleStep = (stepId: number) => {
    setCompletedSteps((prev) => ({
      ...prev,
      [stepId]: !prev[stepId],
    }));
  };

  const completedCount = Object.values(completedSteps).filter(Boolean).length;
  const totalSteps = remediationSteps.length;

  const generateReportText = () => {
    return `=====================================================
VERIOFFER INCIDENT FORENSIC AUDIT REPORT
=====================================================
Report ID: ${id}
Generated: ${timestamp}
Evaluated Sender Domain: ${inputDomain}
Scam Threat Index (STI): ${threatPercentage}%
Threat Classification: ${result.riskTier}
Primary Deception Vector: ${result.primaryDeceptionVector}

EXECUTIVE FINDINGS:
${headline}
${result.executiveSummary}

DETECTED SOCIAL ENGINEERING & PREDATORY RED FLAGS (${result.redFlags.length}):
${result.redFlags.map((rf, idx) => `[FLAG ${idx + 1}] [${rf.severity.toUpperCase()}] ${rf.category}
- Excerpt: "${rf.quote}"
- Analysis: ${rf.explanation}
`).join('\n')}

DOMAIN STRUCTURAL FORENSICS:
- Domain Node: ${result.domainAnalysis.domain}
- Verdict: ${result.domainAnalysis.verdict}
- Details: ${result.domainAnalysis.explanation}

PRIORITIZED REMEDIATION PROTOCOL:
${remediationSteps.map((step) => `[${step.priority.toUpperCase()}] Step ${step.id}: ${step.action}
  Details: ${step.details}
`).join('\n')}

SAFE CONTINGENCY PROTOCOLS:
${safeActions.map((act) => `• ${act}`).join('\n')}

=====================================================
Audit generated by VeriOffer Cyber-SOC Engine
Powered by Google AI Studio (Gemini 3.8 Flash)
Built for PromptWars x Gen AI Challenge
=====================================================`;
  };

  const handleCopyReport = async () => {
    const text = generateReportText();
    await navigator.clipboard.writeText(text);
    setCopiedReport(true);
    setTimeout(() => setCopiedReport(false), 2500);
  };

  const handleDownloadReport = () => {
    const text = generateReportText();
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `VeriOffer_Incident_Report_${id}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const getPriorityStyle = (priority: string) => {
    switch (priority) {
      case 'immediate':
        return 'text-rose-400 bg-rose-500/10 border-rose-500/30';
      case 'recommended':
        return 'text-amber-400 bg-amber-500/10 border-amber-500/30';
      default:
        return 'text-cyan-400 bg-cyan-500/10 border-cyan-500/30';
    }
  };

  return (
    <div className="bg-[#0E1522] border border-slate-800 rounded-xl p-5 shadow-xl space-y-5">
      {/* Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-800">
        <div>
          <div className="flex items-center space-x-2">
            <ShieldCheck className="w-5 h-5 text-emerald-400" />
            <h3 className="text-sm font-bold text-slate-100 font-mono uppercase tracking-wider">
              Action Guard Remediation Protocol
            </h3>
          </div>
          <p className="text-xs text-slate-400 mt-0.5 font-mono">
            Progress: {completedCount}/{totalSteps} containment measures verified
          </p>
        </div>

        {/* Report Export Buttons */}
        <div className="flex items-center space-x-2">
          <button
            onClick={handleCopyReport}
            id="btn-copy-report"
            className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg text-xs font-mono bg-slate-900 text-slate-200 border border-slate-700 hover:border-slate-600 transition-all hover:bg-slate-800"
            title="Copy SOC Incident Report to Clipboard"
          >
            {copiedReport ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-300 font-semibold">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-400" />
                <span>Copy Report</span>
              </>
            )}
          </button>

          <button
            onClick={handleDownloadReport}
            id="btn-download-report"
            className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg text-xs font-mono bg-emerald-500/15 text-emerald-300 border border-emerald-500/30 hover:bg-emerald-500/25 transition-all"
            title="Download Forensic Audit as TXT file"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download .TXT</span>
          </button>
        </div>
      </div>

      {/* Interactive Action Steps */}
      <div className="space-y-2.5">
        {remediationSteps.map((step) => {
          const isDone = !!completedSteps[step.id];
          return (
            <div
              key={step.id}
              onClick={() => toggleStep(step.id)}
              className={`p-3.5 rounded-lg border cursor-pointer transition-all flex items-start space-x-3 ${
                isDone
                  ? 'bg-emerald-950/20 border-emerald-500/30 text-slate-300'
                  : 'bg-[#080C14] border-slate-800 hover:border-slate-700 text-slate-200'
              }`}
            >
              <button
                type="button"
                className="mt-0.5 text-slate-400 hover:text-emerald-400 transition-colors"
                aria-label={`Toggle step ${step.id}`}
              >
                {isDone ? (
                  <CheckSquare className="w-4 h-4 text-emerald-400" />
                ) : (
                  <Square className="w-4 h-4 text-slate-600" />
                )}
              </button>

              <div className="flex-1">
                <div className="flex items-center space-x-2">
                  <span className={`text-[10px] font-mono uppercase px-1.5 py-0.5 rounded border ${getPriorityStyle(step.priority)}`}>
                    {step.priority}
                  </span>
                  <span className={`text-xs font-bold font-mono ${isDone ? 'line-through text-slate-400' : 'text-slate-100'}`}>
                    Step {step.id}: {step.action}
                  </span>
                </div>
                <p className="text-xs text-slate-400 mt-1 leading-relaxed">
                  {step.details}
                </p>
              </div>
            </div>
          );
        })}
      </div>

      {/* Safe Practices Callout */}
      {safeActions.length > 0 && (
        <div className="bg-slate-900/60 border border-slate-800 p-4 rounded-xl">
          <div className="flex items-center space-x-2 text-xs font-mono font-bold text-slate-300 uppercase mb-2">
            <LifeBuoy className="w-4 h-4 text-cyan-400" />
            <span>Cyber Safety Contingency Rules:</span>
          </div>
          <ul className="space-y-1.5 text-xs text-slate-400">
            {safeActions.map((action, idx) => (
              <li key={idx} className="flex items-start space-x-2">
                <span className="text-emerald-400 font-bold">•</span>
                <span>{action}</span>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
};
